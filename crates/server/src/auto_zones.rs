//! The Runners rows' **demand-zone mark** (owner, 2026-10-26: "carry on with the
//! implementations"): a row whose live price sits inside a live automatic DEMAND zone carries a
//! `zone` object, and the clients draw a small zone mark with the zone's edges and its measured
//! hold rate. Context only: it never notifies and never touches the flame.
//!
//! # Why
//!
//! The automatic supply/demand zones (`packages/chart-core/src/autoZones.ts`, the Levels menu
//! layer) were tested after they shipped: research/auto-zones-hold (pre-registered, 118
//! never-read days, Runners stocks) found retested zones held 59–67% of the time against 47–59%
//! for random zones of the same kind, height and distance, +8.6 to +11.4 pp by timeframe, every
//! interval above zero. A level that respects price, not a trade: random levels hold about half
//! the time too, which is why the clients' label gives both numbers.
//!
//! # What is computed
//!
//! [`auto_zones`] is the TS rule ported exactly (same rules, same order of operations, same
//! floats from the same wire candles): `auto_zones_fixtures.json`, generated by
//! `packages/chart-core/scripts/autoZoneFixtures.ts` from the TS function, is checked here zone
//! for zone. Its input is the symbol's COMPLETED 1-minute candles of its latest trading date
//! (`ChartEngine::day_candles`), so two choices differ from a chart: the forming candle is left
//! out (the zones then change only when a minute completes, which is what lets [`ZoneCache`]
//! recompute once a minute instead of every second), and so are earlier days (the mark is about
//! today's structure). The live price for "inside" is the row's own `last`.
//!
//! # Cost
//!
//! Measured on 40 symbols with a full 04:00–20:00 day of 1-minute candles (960 each): see the
//! `cost` test, which fails if one full recompute of all of them takes more than 50 ms in a debug
//! build. In production the cache recomputes a symbol only when its completed-candle count or last
//! candle changes, at most once a minute per Runners symbol; every other frame is a lookup.

use std::collections::HashMap;

use chart_engine::wire::CandleWire;
use chart_engine::{ChartEngine, Timeframe};
use serde_json::{Value, json};

/// `AUTO_ZONE_RULES` in autoZones.ts. Change them in both places or neither.
const ATR_N: usize = 14;
const BASE_MAX: usize = 5;
const BASE_RANGE_ATR: f64 = 1.0;
const LEG_MAX: usize = 3;
const LEG_ATR: f64 = 2.0;
const DECISIVE_BODY: f64 = 0.6;
const PER_SIDE: usize = 3;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ZoneKind {
    Supply,
    Demand,
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct AutoZone {
    pub kind: ZoneKind,
    pub lo: f64,
    pub hi: f64,
    /// Start of the first base candle, epoch ms.
    pub t: i64,
    pub tested: bool,
}

fn body(c: &CandleWire) -> f64 {
    (c.c - c.o).abs()
}

fn range(c: &CandleWire) -> f64 {
    c.h - c.l
}

/// The active zones for `cs` (oldest first), at most [`PER_SIDE`] per kind, nearest the last close
/// first, then ordered by `t`: autoZones() in autoZones.ts, line for line.
pub fn auto_zones(cs: &[CandleWire]) -> Vec<AutoZone> {
    if cs.len() < ATR_N + 3 {
        return Vec::new();
    }
    let tr: Vec<f64> = cs
        .iter()
        .enumerate()
        .map(|(i, c)| {
            if i == 0 {
                range(c)
            } else {
                let pc = cs[i - 1].c;
                range(c).max((c.h - pc).abs()).max((c.l - pc).abs())
            }
        })
        .collect();
    let atr_before = |i: usize| -> f64 {
        if i < ATR_N {
            return f64::NAN;
        }
        // Summed in the same order as the TS loop, so the float is identical.
        let mut s = 0.0;
        for x in &tr[i - ATR_N..i] {
            s += x;
        }
        s / ATR_N as f64
    };
    let quiet = |c: &CandleWire, atr: f64| {
        range(c) > 0.0 && body(c) <= range(c) * 0.5 && range(c) <= BASE_RANGE_ATR * atr
    };

    struct Found {
        zone: AutoZone,
        leg_end: usize,
        distal: f64,
    }
    let mut found: Vec<Found> = Vec::new();
    let mut i = ATR_N;
    while i < cs.len() - 1 {
        let atr = atr_before(i);
        // `!(atr > 0)` in TS: NaN is not quiet either (`partial_cmp` is None for NaN).
        if atr.partial_cmp(&0.0) != Some(std::cmp::Ordering::Greater) || !quiet(&cs[i], atr) {
            i += 1;
            continue;
        }
        let mut j = i;
        while j + 1 < cs.len() && j - i + 1 < BASE_MAX && quiet(&cs[j + 1], atr) {
            j += 1;
        }
        let base = &cs[i..=j];
        let base_high = base.iter().map(|c| c.h).fold(f64::NEG_INFINITY, f64::max);
        let base_low = base.iter().map(|c| c.l).fold(f64::INFINITY, f64::min);
        let body_top = base
            .iter()
            .map(|c| c.o.max(c.c))
            .fold(f64::NEG_INFINITY, f64::max);
        let body_bottom = base
            .iter()
            .map(|c| c.o.min(c.c))
            .fold(f64::INFINITY, f64::min);
        let mut made = false;
        if let Some(first) = cs.get(j + 1)
            && body(first) >= DECISIVE_BODY * range(first)
        {
            let up = first.c > base_high;
            let down = first.c < base_low;
            if up || down {
                let mut reach = 0.0;
                let mut end = j + 1;
                for (k, c) in cs
                    .iter()
                    .enumerate()
                    .take(cs.len().min(j + 1 + LEG_MAX))
                    .skip(j + 1)
                {
                    let d = if up { c.h - base_high } else { base_low - c.l };
                    if d > reach {
                        reach = d;
                        end = k;
                    }
                }
                if reach >= LEG_ATR * atr {
                    let zone = if up {
                        AutoZone {
                            kind: ZoneKind::Demand,
                            lo: base_low,
                            hi: body_top,
                            t: base[0].t,
                            tested: false,
                        }
                    } else {
                        AutoZone {
                            kind: ZoneKind::Supply,
                            lo: body_bottom,
                            hi: base_high,
                            t: base[0].t,
                            tested: false,
                        }
                    };
                    if zone.hi > zone.lo {
                        found.push(Found {
                            zone,
                            leg_end: end,
                            distal: if up { base_low } else { base_high },
                        });
                    }
                    made = true;
                }
            }
        }
        i = if made { j + 1 } else { i + 1 };
    }

    let mut live: Vec<AutoZone> = Vec::new();
    for f in &found {
        let mut broken = false;
        let mut tested = false;
        for c in &cs[(f.leg_end + 1).min(cs.len())..] {
            let through = match f.zone.kind {
                ZoneKind::Demand => c.c < f.distal,
                ZoneKind::Supply => c.c > f.distal,
            };
            if through {
                broken = true;
                break;
            }
            if match f.zone.kind {
                ZoneKind::Demand => c.l <= f.zone.hi,
                ZoneKind::Supply => c.h >= f.zone.lo,
            } {
                tested = true;
            }
        }
        if !broken {
            live.push(AutoZone { tested, ..f.zone });
        }
    }

    let mut kept: Vec<AutoZone> = Vec::new();
    for z in live {
        if !kept
            .iter()
            .any(|k| k.kind == z.kind && z.lo <= k.hi && z.hi >= k.lo)
        {
            kept.push(z);
        }
    }

    let last = cs[cs.len() - 1].c;
    let dist = |z: &AutoZone| (z.lo - last).abs().min((z.hi - last).abs());
    let nearest = |kind: ZoneKind| {
        let mut v: Vec<AutoZone> = kept.iter().copied().filter(|z| z.kind == kind).collect();
        // Stable, like Array.prototype.sort: equal distances keep their order.
        v.sort_by(|a, b| dist(a).total_cmp(&dist(b)));
        v.truncate(PER_SIDE);
        v
    };
    let mut out = nearest(ZoneKind::Supply);
    out.extend(nearest(ZoneKind::Demand));
    out.sort_by_key(|z| z.t);
    out
}

/// The demand zone `price` is inside, if any: the latest-formed one when several overlap the
/// price (they cannot overlap each other, `kept` above; a price on a shared edge can touch two).
pub fn demand_zone_at(zones: &[AutoZone], price: f64) -> Option<AutoZone> {
    zones
        .iter()
        .filter(|z| z.kind == ZoneKind::Demand && z.lo <= price && price <= z.hi)
        .max_by_key(|z| z.t)
        .copied()
}

/// Per-symbol zones, recomputed only when the symbol's completed candles change (module docs,
/// "Cost"). Keyed on the count and the last candle's start and close: a completed candle never
/// changes, except a late correction, which moves the close and is caught.
#[derive(Debug, Default)]
pub struct ZoneCache {
    by_symbol: HashMap<String, (CacheKey, Vec<AutoZone>)>,
}

/// Completed-candle count, last candle start (ms) and its close's bits.
type CacheKey = (usize, i64, u64);

impl ZoneCache {
    fn zones(&mut self, engine: &ChartEngine, symbol: &str) -> Vec<AutoZone> {
        let Some(cs) = engine.day_candles(symbol, Timeframe::M1) else {
            self.by_symbol.remove(symbol);
            return Vec::new();
        };
        let key = cs
            .last()
            .map_or((0, 0, 0), |c| (cs.len(), c.t, c.c.to_bits()));
        if let Some((k, z)) = self.by_symbol.get(symbol)
            && *k == key
        {
            return z.clone();
        }
        let z = auto_zones(&cs);
        self.by_symbol.insert(symbol.to_owned(), (key, z.clone()));
        z
    }

    /// Adds `zone` to every row of a Runners frame body whose `last` price is inside a live demand
    /// zone (module docs). Rows keep their order; symbols no longer listed leave the cache, so it
    /// is bounded by the panel. Additive on the wire: an older client ignores the key.
    pub fn decorate(&mut self, engine: &ChartEngine, body: &mut Value) {
        let Some(rows) = body.get_mut("rows").and_then(Value::as_array_mut) else {
            return;
        };
        let mut seen: Vec<String> = Vec::with_capacity(rows.len());
        for row in rows.iter_mut() {
            let Some(m) = row.as_object_mut() else {
                continue;
            };
            let Some(symbol) = m.get("s").and_then(Value::as_str).map(str::to_owned) else {
                continue;
            };
            let last = m.get("last").and_then(Value::as_f64);
            let zones = self.zones(engine, &symbol);
            seen.push(symbol);
            if let Some(z) = last.and_then(|p| demand_zone_at(&zones, p)) {
                m.insert(
                    "zone".into(),
                    json!({ "lo": z.lo, "hi": z.hi, "tested": z.tested, "formed_t": z.t }),
                );
            }
        }
        self.by_symbol.retain(|s, _| seen.contains(s));
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn c(t: i64, o: f64, h: f64, l: f64, cl: f64) -> CandleWire {
        CandleWire {
            t,
            o,
            h,
            l,
            c: cl,
            v: 1000,
            n: 10,
            is_final: true,
        }
    }

    #[derive(serde::Deserialize)]
    struct Fixture {
        name: String,
        candles: Vec<[f64; 5]>,
        zones: Vec<FixZone>,
    }
    #[derive(serde::Deserialize)]
    struct FixZone {
        kind: String,
        lo: f64,
        hi: f64,
        t: i64,
        tested: bool,
    }

    /// The port gives exactly the zones autoZones.ts gives on the generated fixtures (bit-equal
    /// floats, same order, same tested flags).
    #[test]
    fn parity_with_the_ts_rule() {
        let fx: Vec<Fixture> =
            serde_json::from_str(include_str!("auto_zones_fixtures.json")).unwrap();
        assert!(fx.len() >= 50, "fixtures: {}", fx.len());
        let mut zones = 0;
        for f in &fx {
            let cs: Vec<CandleWire> = f
                .candles
                .iter()
                .map(|x| c(x[0] as i64, x[1], x[2], x[3], x[4]))
                .collect();
            let got = auto_zones(&cs);
            assert_eq!(got.len(), f.zones.len(), "{}: count", f.name);
            for (g, w) in got.iter().zip(&f.zones) {
                let kind = if g.kind == ZoneKind::Demand {
                    "demand"
                } else {
                    "supply"
                };
                assert_eq!(kind, w.kind, "{}", f.name);
                assert_eq!(g.lo.to_bits(), w.lo.to_bits(), "{}: lo", f.name);
                assert_eq!(g.hi.to_bits(), w.hi.to_bits(), "{}: hi", f.name);
                assert_eq!(g.t, w.t, "{}: t", f.name);
                assert_eq!(g.tested, w.tested, "{}: tested", f.name);
            }
            zones += got.len();
        }
        assert!(
            zones >= 50,
            "the fixtures must exercise real zones: {zones}"
        );
    }

    /// The test case autoZones.test.ts uses: a quiet base then a decisive rally is a demand zone,
    /// and the price inside it finds it.
    fn warmup(p: f64) -> Vec<CandleWire> {
        (0..14)
            .map(|i| {
                c(
                    i * 60_000,
                    p,
                    p + 0.06,
                    p - 0.04,
                    if i % 2 == 1 { p + 0.04 } else { p - 0.02 },
                )
            })
            .collect()
    }

    #[test]
    fn demand_zone_and_price_inside() {
        let mut cs = warmup(5.0);
        cs.push(c(14 * 60_000, 5.0, 5.04, 4.96, 5.01));
        cs.push(c(15 * 60_000, 5.01, 5.05, 4.98, 5.0));
        cs.push(c(16 * 60_000, 5.0, 5.4, 4.99, 5.38));
        cs.push(c(17 * 60_000, 5.38, 5.5, 5.36, 5.48));
        let z = auto_zones(&cs);
        assert_eq!(z.len(), 1);
        assert_eq!(
            (z[0].kind, z[0].lo, z[0].hi),
            (ZoneKind::Demand, 4.96, 5.01)
        );
        assert!(demand_zone_at(&z, 4.99).is_some());
        assert!(demand_zone_at(&z, 5.2).is_none());
        // A supply zone never answers a demand query.
        let s = AutoZone {
            kind: ZoneKind::Supply,
            ..z[0]
        };
        assert!(demand_zone_at(&[s], 4.99).is_none());
    }

    /// The wire: a row whose `last` is inside a live demand zone gets `zone`, others none; a symbol
    /// that leaves the panel leaves the cache. Candles built by the real chart engine from trades.
    #[test]
    fn rows_get_the_zone_their_price_is_in() {
        use chrono::NaiveDate;
        use market_events::session::et;
        use market_events::{MarketEvent, Source as Feed, Tape, Trade};
        let at = |m: u32, s: u32| {
            et(NaiveDate::from_ymd_opt(2026, 10, 26).unwrap(), 4, m, s, 0).unwrap()
        };
        let mut e = ChartEngine::default();
        let mut seq = 0;
        let mut candles = warmup(5.0);
        candles.push(c(14, 5.0, 5.04, 4.96, 5.01));
        candles.push(c(15, 5.01, 5.05, 4.98, 5.0));
        candles.push(c(16, 5.0, 5.4, 4.99, 5.38));
        candles.push(c(17, 5.38, 5.5, 5.36, 5.48));
        for (m, k) in candles.iter().enumerate() {
            // o, h, l, c inside the minute, so the engine's 1-minute candle is exactly `k`.
            for (s, p) in [(1, k.o), (10, k.h), (20, k.l), (50, k.c)] {
                seq += 1;
                e.apply(&MarketEvent::Trade(
                    Trade::new(
                        "AAAA",
                        at(m as u32, s),
                        format!("{p:.2}").parse().unwrap(),
                        100,
                        seq,
                    )
                    .with_exchange("V")
                    .with_tape(Tape::C)
                    .with_source(Feed::Fixture),
                ));
            }
        }
        e.advance_clock(at(candles.len() as u32, 1));
        let mut cache = ZoneCache::default();
        let mut body = json!({ "rows": [
            { "s": "AAAA", "last": 4.99 },
            { "s": "AAAA", "last": 5.3 },
            { "s": "NONE", "last": 1.0 },
        ] });
        cache.decorate(&e, &mut body);
        let zone = &body["rows"][0]["zone"];
        assert_eq!(zone["lo"], 4.96);
        assert_eq!(zone["hi"], 5.01);
        assert_eq!(zone["tested"], false);
        assert_eq!(zone["formed_t"], at(14, 0).0 / 1_000_000);
        assert!(body["rows"][1].get("zone").is_none(), "above the zone");
        assert!(body["rows"][2].get("zone").is_none(), "no candles");
        // AAAA leaves the panel: it leaves the cache too.
        cache.decorate(&e, &mut json!({ "rows": [] }));
        assert!(cache.by_symbol.is_empty());
    }

    /// Module docs, "Cost": 40 Runners symbols with a whole 960-candle day each, built from the
    /// fixture days (which form real zones, so the forward walks are exercised too).
    #[test]
    fn cost() {
        let fx: Vec<Fixture> =
            serde_json::from_str(include_str!("auto_zones_fixtures.json")).unwrap();
        let day: Vec<CandleWire> = fx
            .iter()
            .filter(|f| f.candles.len() == 480)
            .take(2)
            .flat_map(|f| f.candles.iter())
            .enumerate()
            .map(|(i, x)| c(i as i64 * 60_000, x[1], x[2], x[3], x[4]))
            .collect();
        assert_eq!(day.len(), 960);
        let t = std::time::Instant::now();
        let mut n = 0;
        for _ in 0..40 {
            n += auto_zones(&day).len();
        }
        let took = t.elapsed();
        eprintln!("auto_zones cost: 40 × 960 candles in {took:?} ({n} zones)");
        assert!(took.as_millis() < 50, "40 full recomputes took {took:?}");
    }
}
