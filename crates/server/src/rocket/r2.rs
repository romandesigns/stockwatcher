//! `precursors-R2`: the rocket bake-off's round-2 runner-up, a LightGBM model on the research's
//! precursor features, ready to replace `precursors-R0` once the judge confirms it
//! (`RUNNERS_SCORER=r2`; the default stays `r0` until then, see [`super::scorer::ScorerChoice`]).
//!
//! # What it is
//!
//! Frozen on research branch `research/rocket-precursors` at commit `65ca7c9`
//! (`C:\research\stockwatcher\reports\rockets\candidates\precursors-R2\frozen-round2.json`, round 2
//! of protocol v3: fitted on DEV-2 = 112 days, 2026-03-23..10-20 minus the TEST days). A binary
//! LightGBM 4.7.0 classifier for "a rocket starts 1–10 min after this barrier": 300 trees of at
//! most 15 leaves (depth ≤ 4) on 26 of the 31 features ([`super::FEATS`] minus `range5` and the
//! four news counts). The score is the model's RAW score (log-odds, the sum of the leaf values),
//! as in the research's score pass, and the alert threshold is the frozen B10 one (10 alerts a
//! day on DEV-2), so the alert count follows the market like R0's.
//!
//! (Round 1, `frozen.json` @ `c009126`, fitted the same recipe on the 11 round-1 DEV days, with
//! B10 = 2.5599…; it is superseded by this round-2 refit and not shipped.)
//!
//! # Evaluation, exactly as the research
//!
//! 1. Gather the 26 model features from `x` in the model's order.
//! 2. A missing feature (`NaN`) is replaced by the frozen training MEDIAN for it (`fit.py
//!    fit_gbt` / `score_py`, the research's Rust `Model::Gbt`). The trees were trained on
//!    imputed data, so LightGBM recorded `missing_type=None` for every split: its own NaN rule
//!    (NaN → 0.0, then the comparison) never comes into play, and NO NaN ever reaches a tree here.
//! 3. Each tree: from the root, `x[f] <= t` goes left, else right, to a leaf. The score is
//!    `0.0 + leaf₁ + leaf₂ + … + leaf₃₀₀` in tree order: the same additions in the same order as
//!    LightGBM's `predict(raw_score=True)`, so the result is bit-identical, not just close.
//!
//! The model is `r2_model.txt` beside this file, embedded at compile time and parsed once on
//! first use: no Python or LightGBM at run time. It and the parity vectors (`r2_parity.csv`, 300
//! research feature rows from five days with LightGBM's own raw score) are generated by
//! `r2_export.py`, whose doc says how the LightGBM booster was recovered from the frozen JSON.
//! Floats are written shortest-round-trip and parsed with `str::parse::<f64>` (correctly rounded),
//! so every threshold and leaf value is the frozen double.
//!
//! # Known gap against the research (affects the score, not the evaluator)
//!
//! The server's `pdh` (previous day's high) and `rvol` (30-day relative volume) are always `NaN`
//! (`features` module docs, "Differences"), so they always take their medians here. They carry
//! 2.8 % and 1.6 % of the model's split gain; the research rows had them. A live R2 score is
//! therefore the research model's score on a symbol whose `pdh`/`rvol` are typical, which shifts
//! some scores near the threshold. Wiring those two features in removes the gap.
//!
//! # Cost
//!
//! ~1,200 comparisons per scored symbol (300 trees × ≤ 4 levels), no allocation: well under a
//! millisecond per thousand symbols; `rocket::tests::r2_cost_per_barrier` measures ~7k.

use std::sync::OnceLock;

use super::features::{FEATS, Features, NF};
use super::scorer::{RocketScorer, standard_reasons};

const MODEL_TXT: &str = include_str!("r2_model.txt");
/// Features the model reads, at most.
const MAX_FEATS: usize = NF;

/// One split. `left`/`right` >= 0 are node indexes in the same tree, < 0 are leaves `-(i + 1)`.
#[derive(Clone, Copy, Debug)]
struct Node {
    feat: u8,
    thr: f64,
    left: i32,
    right: i32,
}

#[derive(Debug)]
struct Tree {
    nodes: Vec<Node>,
    leaves: Vec<f64>,
}

/// The parsed frozen model.
#[derive(Debug)]
pub struct R2Model {
    /// For each model feature, its index into [`Features::x`].
    idx: Vec<usize>,
    med: Vec<f64>,
    trees: Vec<Tree>,
    /// The frozen thresholds: B5, B10, B20.
    pub theta_b5: f64,
    pub theta_b10: f64,
    pub theta_b20: f64,
    pub commit: String,
    pub source_sha256: String,
}

/// A tree being read: its split features, thresholds, left and right children.
type Pending = (Vec<u8>, Vec<f64>, Vec<i32>, Vec<i32>);

fn nums<T: std::str::FromStr>(rest: &str, what: &str) -> Result<Vec<T>, String> {
    rest.split_ascii_whitespace()
        .map(|s| {
            s.parse::<T>()
                .map_err(|_| format!("{what}: bad number {s:?}"))
        })
        .collect()
}

impl R2Model {
    /// Parses `r2_model.txt` (format: `r2_export.py`). Every structural assumption the
    /// evaluator relies on is checked here, once, so `raw` cannot index out of bounds or loop.
    pub fn parse(txt: &str) -> Result<R2Model, String> {
        let mut m = R2Model {
            idx: Vec::new(),
            med: Vec::new(),
            trees: Vec::new(),
            theta_b5: f64::NAN,
            theta_b10: f64::NAN,
            theta_b20: f64::NAN,
            commit: String::new(),
            source_sha256: String::new(),
        };
        // A tree is five lines after its `tree` marker: f, t, l, r, v.
        let mut cur: Option<Pending> = None;
        for (n, line) in txt.lines().enumerate() {
            let line = line.trim_end();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let (key, rest) = line.split_once(' ').unwrap_or((line, ""));
            let at = |e: String| format!("r2_model.txt line {}: {e}", n + 1);
            match key {
                "commit" => m.commit = rest.to_string(),
                "source_sha256" => m.source_sha256 = rest.to_string(),
                "candidate" | "round" | "lightgbm" => {}
                "theta" => {
                    let (b, v) = rest.split_once(' ').ok_or_else(|| at("theta".into()))?;
                    let v: f64 = v.parse().map_err(|_| at(format!("theta {v:?}")))?;
                    match b {
                        "B5" => m.theta_b5 = v,
                        "B10" => m.theta_b10 = v,
                        "B20" => m.theta_b20 = v,
                        _ => return Err(at(format!("unknown budget {b}"))),
                    }
                }
                "feats" => {
                    for name in rest.split_ascii_whitespace() {
                        let i = FEATS
                            .iter()
                            .position(|f| *f == name)
                            .ok_or_else(|| at(format!("unknown feature {name}")))?;
                        m.idx.push(i);
                    }
                }
                "med" => m.med = nums(rest, "med").map_err(at)?,
                "tree" => cur = Some(Default::default()),
                "f" => {
                    cur.as_mut().ok_or_else(|| at("f before tree".into()))?.0 =
                        nums(rest, "f").map_err(at)?
                }
                "t" => {
                    cur.as_mut().ok_or_else(|| at("t before tree".into()))?.1 =
                        nums(rest, "t").map_err(at)?
                }
                "l" => {
                    cur.as_mut().ok_or_else(|| at("l before tree".into()))?.2 =
                        nums(rest, "l").map_err(at)?
                }
                "r" => {
                    cur.as_mut().ok_or_else(|| at("r before tree".into()))?.3 =
                        nums(rest, "r").map_err(at)?
                }
                "v" => {
                    let (f, t, l, r) = cur.take().ok_or_else(|| at("v before tree".into()))?;
                    let leaves: Vec<f64> = nums(rest, "v").map_err(at)?;
                    let k = f.len();
                    if t.len() != k || l.len() != k || r.len() != k || leaves.len() != k + 1 {
                        return Err(at(format!(
                            "tree shape: {k} splits, {} thresholds, {} leaves",
                            t.len(),
                            leaves.len()
                        )));
                    }
                    let child_ok = |c: i32, from: usize| {
                        if c < 0 {
                            ((-c - 1) as usize) < leaves.len()
                        } else {
                            // Children come after their parent (pre-order), so walks end.
                            (c as usize) > from && (c as usize) < k
                        }
                    };
                    let mut nodes = Vec::with_capacity(k);
                    for i in 0..k {
                        if !child_ok(l[i], i) || !child_ok(r[i], i) || !t[i].is_finite() {
                            return Err(at(format!("tree node {i} is malformed")));
                        }
                        nodes.push(Node {
                            feat: f[i],
                            thr: t[i],
                            left: l[i],
                            right: r[i],
                        });
                    }
                    m.trees.push(Tree { nodes, leaves });
                }
                _ => return Err(at(format!("unknown key {key:?}"))),
            }
        }
        let nf = m.idx.len();
        if nf == 0 || nf > MAX_FEATS || m.med.len() != nf {
            return Err(format!("{nf} features, {} medians", m.med.len()));
        }
        if m.med.iter().any(|x| !x.is_finite()) {
            return Err("a median is not finite".into());
        }
        if m.trees.is_empty() || cur.is_some() {
            return Err("no trees, or a tree without its leaves".into());
        }
        if m.trees
            .iter()
            .any(|t| t.nodes.iter().any(|n| usize::from(n.feat) >= nf))
        {
            return Err("a split on a feature the model does not have".into());
        }
        if ![m.theta_b5, m.theta_b10, m.theta_b20]
            .iter()
            .all(|x| x.is_finite())
        {
            return Err("missing frozen thresholds".into());
        }
        Ok(m)
    }

    /// The model's raw score (log-odds) for the research feature vector `x` ([`super::FEATS`]
    /// order, `NaN` = missing). Module docs, "Evaluation".
    pub fn raw(&self, x: &[f64; NF]) -> f64 {
        let mut v = [0.0f64; MAX_FEATS];
        for (n, &i) in self.idx.iter().enumerate() {
            let a = x[i];
            v[n] = if a.is_nan() { self.med[n] } else { a };
        }
        let mut z = 0.0;
        for t in &self.trees {
            if t.nodes.is_empty() {
                z += t.leaves[0];
                continue;
            }
            let mut node = 0usize;
            loop {
                let s = t.nodes[node];
                let next = if v[usize::from(s.feat)] <= s.thr {
                    s.left
                } else {
                    s.right
                };
                if next < 0 {
                    z += t.leaves[(-next - 1) as usize];
                    break;
                }
                node = next as usize;
            }
        }
        z
    }

    pub fn trees(&self) -> usize {
        self.trees.len()
    }
}

/// The embedded frozen model, parsed on first use. A malformed file is a build defect, caught by
/// the tests (`the_embedded_model_parses`), so this panics rather than limping on.
pub fn model() -> &'static R2Model {
    static M: OnceLock<R2Model> = OnceLock::new();
    M.get_or_init(|| R2Model::parse(MODEL_TXT).expect("embedded r2_model.txt"))
}

pub struct PrecursorsR2 {
    m: &'static R2Model,
}

impl PrecursorsR2 {
    pub fn new() -> Self {
        PrecursorsR2 { m: model() }
    }
}

impl Default for PrecursorsR2 {
    fn default() -> Self {
        Self::new()
    }
}

impl RocketScorer for PrecursorsR2 {
    fn id(&self) -> &str {
        "precursors-R2"
    }
    fn version(&self) -> &str {
        &self.m.commit
    }
    /// Every unit barrier gets a score (no gate): missing features take their medians.
    fn score(&self, f: &Features) -> Option<f64> {
        Some(self.m.raw(&f.x))
    }
    /// The frozen B10 threshold (10 alerts a day on DEV-2).
    fn fixed_threshold(&self) -> Option<f64> {
        Some(self.m.theta_b10)
    }
    fn reasons(&self, f: &Features) -> Vec<String> {
        standard_reasons(f)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const PARITY: &str = include_str!("r2_parity.csv");

    fn parity_rows() -> Vec<([f64; NF], f64)> {
        let mut lines = PARITY.lines();
        let head: Vec<&str> = lines.next().unwrap().trim().split(',').collect();
        assert_eq!(
            &head[..NF],
            &FEATS[..],
            "parity columns are the server's FEATS"
        );
        assert_eq!(head[NF], "lightgbm_raw");
        lines
            .map(|l| {
                let v: Vec<f64> = l
                    .trim()
                    .split(',')
                    .map(|s| s.parse::<f64>().expect("number"))
                    .collect();
                assert_eq!(v.len(), NF + 1);
                let mut x = [0.0; NF];
                x.copy_from_slice(&v[..NF]);
                (x, v[NF])
            })
            .collect()
    }

    #[test]
    fn the_embedded_model_parses() {
        let m = model();
        assert_eq!(m.trees(), 300);
        assert_eq!(m.idx.len(), 26);
        assert_eq!(m.commit, "65ca7c9");
        assert_eq!(m.theta_b10, 3.059_471_204_774_817);
        assert_eq!(m.theta_b5, 3.261_248_721_302_36);
        assert_eq!(m.theta_b20, 2.816_185_410_978_512);
        assert!(m.trees.iter().all(|t| t.nodes.len() < 15));
    }

    /// LightGBM's own raw score on 300 research rows (incl. 116 with missing features).
    #[test]
    fn parity_with_lightgbm_raw_score() {
        let m = model();
        let rows = parity_rows();
        assert!(rows.len() >= 200, "{} parity rows", rows.len());
        let with_nan = rows
            .iter()
            .filter(|(x, _)| x.iter().any(|v| v.is_nan()))
            .count();
        assert!(with_nan >= 50, "{with_nan} rows with a missing feature");
        let mut worst = 0.0f64;
        let mut exact = 0;
        for (i, (x, want)) in rows.iter().enumerate() {
            let got = m.raw(x);
            let d = (got - want).abs();
            assert!(d <= 1e-9, "row {i}: {got} vs LightGBM {want}");
            worst = worst.max(d);
            exact += usize::from(got.to_bits() == want.to_bits());
        }
        eprintln!(
            "r2 parity: {} rows, max |rust - lightgbm| = {worst:e}, bit-identical {exact}",
            rows.len()
        );
        // Same additions in the same order as LightGBM: not just close, identical.
        assert_eq!(exact, rows.len());
        let above = rows.iter().filter(|(_, s)| *s >= m.theta_b10).count();
        assert!(above > 0, "the parity set reaches the alert threshold");
    }

    #[test]
    fn a_missing_feature_takes_its_median() {
        let m = model();
        let (x, _) = parity_rows()[0];
        for (n, &i) in m.idx.iter().enumerate() {
            let mut a = x;
            let mut b = x;
            a[i] = f64::NAN;
            b[i] = m.med[n];
            assert_eq!(
                m.raw(&a).to_bits(),
                m.raw(&b).to_bits(),
                "feature {}",
                FEATS[i]
            );
        }
        // Features the model does not read never matter.
        let mut c = x;
        for i in [
            super::super::ix::RANGE5,
            super::super::ix::N15,
            super::super::ix::NDAY,
        ] {
            c[i] = 123.0;
        }
        assert_eq!(m.raw(&c).to_bits(), m.raw(&x).to_bits());
        // All missing: a finite score.
        assert!(m.raw(&[f64::NAN; NF]).is_finite());
    }

    #[test]
    fn malformed_models_are_refused() {
        assert!(R2Model::parse("").is_err());
        let good = MODEL_TXT;
        assert!(R2Model::parse(&good.replace("feats logp", "feats nope")).is_err());
        assert!(R2Model::parse(&good.replace("theta B10", "theta B11")).is_err());
        // A child pointing backwards (a loop) is refused.
        let bad = good.replacen("\nl 1 ", "\nl 0 ", 1);
        assert_ne!(bad, good);
        assert!(R2Model::parse(&bad).is_err());
    }

    #[test]
    fn the_scorer_is_fixed_at_b10() {
        let s = PrecursorsR2::new();
        assert_eq!(s.id(), "precursors-R2");
        assert_eq!(s.version(), "65ca7c9");
        assert_eq!(s.fixed_threshold(), Some(model().theta_b10));
        assert!(!s.placeholder());
    }
}
