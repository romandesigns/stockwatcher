"""Regenerates `r2_model.txt` and `r2_parity.csv` (the `precursors-R2` scorer, `r2.rs`).

NOT run by the build: the two files are committed. Kept so their provenance is checkable.

    python r2_export.py FROZEN_ROUND2_JSON BOOSTER_TXT EXPORT_DIR OUT_DIR

- FROZEN_ROUND2_JSON: `reports/rockets/candidates/precursors-R2/frozen-round2.json` (research
  branch `research/rocket-precursors` @ 65ca7c9). Its `model` is LightGBM 4.7.0's dump, flattened
  by `fit.py flat_tree`.
- BOOSTER_TXT: the same model as a LightGBM booster file. The frozen JSON keeps only the
  flattened trees, so it was refitted with `fit.py`'s exact recipe (round 2, seed 7,
  `deterministic=True`, DEV-2 = 112 days, 3,535,352 rows) and `save_model`d; the refit's dumped
  trees and medians compare EQUAL to the frozen ones (asserted below), so its raw score is the
  frozen model's. This is what lets the parity vectors be LightGBM's own `predict(raw_score=True)`
  rather than a re-implementation's.
- EXPORT_DIR: `reports/rockets/export` (the research feature rows, `rows-<day>.csv`).

Floats are written with `repr` (shortest round-trip) and read in Rust with `str::parse::<f64>`,
which is correctly rounded, so every threshold and leaf value is bit-exact. (serde_json without
its `float_roundtrip` feature may be one ulp off, which is why the model is not read as JSON.)
"""
import hashlib
import json
import os
import sys

import lightgbm as lgb
import numpy as np
import pandas as pd

# The server's `features::FEATS` order (= research `rocket.rs` FEATS = fit.py ALL).
FEATS = ["logp", "range30", "range60", "range5", "idle30", "vr1", "vr3", "vr5", "tr3", "dv5", "grind",
         "upc3", "ret1", "ret3", "ret5", "ret15", "upt3", "odd3", "blk3", "dhi", "pdh", "gain", "gap",
         "rvol", "vwap", "tod", "sess", "n15", "n60", "n240", "nday"]
# Parity days: two DEV-2 days, two round-2 TEST days, one late day (all seen by the research).
DAYS = ["2026-05-14", "2026-08-12", "2026-09-10", "2026-10-16", "2026-10-20"]


def flat_tree(t):
    f, th, l, r, v = [], [], [], [], []

    def walk(n):
        if "leaf_value" in n:
            v.append(n["leaf_value"])
            return -len(v)
        i = len(f)
        f.append(n["split_feature"]); th.append(n["threshold"]); l.append(0); r.append(0)
        assert n["decision_type"] == "<=", n["decision_type"]
        # missing_type None: LightGBM itself would map NaN to 0.0 here. The recipe never lets a
        # NaN reach the trees (median imputation first), so that path is unused.
        assert n["missing_type"] == "None", n["missing_type"]
        l[i] = walk(n["left_child"])
        r[i] = walk(n["right_child"])
        return i

    root = t["tree_structure"]
    if "leaf_value" in root:
        return {"f": [], "t": [], "l": [], "r": [], "v": [root["leaf_value"]]}
    walk(root)
    return {"f": f, "t": th, "l": l, "r": r, "v": v}


def main():
    frozen_p, booster_p, export, out = sys.argv[1:5]
    raw = open(frozen_p, "rb").read()
    fz = json.loads(raw)
    m = fz["model"]
    assert fz["candidate"] == "precursors-R2" and fz["round"] == 2 and m["kind"] == "gbt"
    bst = lgb.Booster(model_file=booster_p)
    trees = [flat_tree(t) for t in bst.dump_model()["tree_info"]]
    assert trees == m["trees"], "booster is not the frozen model"
    feats, med = m["feats"], np.array(m["med"])

    w = repr
    lines = [
        "# precursors-R2 (research/rocket-precursors), generated by r2_export.py. Do not edit.",
        f"candidate {fz['candidate']}",
        f"round {fz['round']}",
        f"commit {fz['commit']}",
        f"lightgbm {fz['versions']['lightgbm']}",
        f"source_sha256 {hashlib.sha256(raw).hexdigest()}",
    ]
    for b in ("B5", "B10", "B20"):
        lines.append(f"theta {b} {w(fz['thresholds'][b]['theta'])}")
    lines.append("feats " + " ".join(feats))
    lines.append("med " + " ".join(w(float(x)) for x in med))
    for t in m["trees"]:
        lines.append("tree")
        lines.append("f " + " ".join(str(x) for x in t["f"]))
        lines.append("t " + " ".join(w(float(x)) for x in t["t"]))
        lines.append("l " + " ".join(str(x) for x in t["l"]))
        lines.append("r " + " ".join(str(x) for x in t["r"]))
        lines.append("v " + " ".join(w(float(x)) for x in t["v"]))
    with open(os.path.join(out, "r2_model.txt"), "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")

    # Parity vectors: per day 30 random rows, the 20 highest-scoring and 10 with features knocked
    # out to NaN (the recipe's median imputation), 300 rows in all. Expected = LightGBM's raw score.
    rng = np.random.default_rng(20261022)
    picked = []
    for d in DAYS:
        x = pd.read_csv(os.path.join(export, f"rows-{d}.csv"))
        x = x.rename(columns={"sess.1": "sess_feat"})
        x["sess"] = x["sess_feat"]  # the feature column (equal to the meta column; fit.py reads the first)
        A = np.where(np.isnan(x[feats].to_numpy(dtype=float)), med, x[feats].to_numpy(dtype=float))
        x["raw"] = bst.predict(A, raw_score=True)
        rnd = x.iloc[rng.choice(len(x), 30, replace=False)]
        top = x.drop(rnd.index).nlargest(20, "raw")
        nan = x.drop(rnd.index).drop(top.index).iloc[rng.choice(len(x) - 50, 10, replace=False)].copy()
        for i in nan.index:
            k = rng.integers(1, 6)
            for f in rng.choice(feats, k, replace=False):
                nan.loc[i, f] = np.nan
        picked += [rnd, top, nan]
    P = pd.concat(picked, ignore_index=True)
    X = P[FEATS].to_numpy(dtype=float)
    A = P[feats].to_numpy(dtype=float)
    A = np.where(np.isnan(A), med, A)
    raw_scores = bst.predict(A, raw_score=True)
    with open(os.path.join(out, "r2_parity.csv"), "w", newline="\n") as fh:
        fh.write(",".join(FEATS + ["lightgbm_raw"]) + "\n")
        for row, s in zip(X, raw_scores):
            fh.write(",".join("nan" if np.isnan(v) else w(float(v)) for v in row) + "," + w(float(s)) + "\n")
    print("rows", len(P), "nan rows", int(np.isnan(X).any(1).sum()),
          "max raw", float(raw_scores.max()), ">= B10", int((raw_scores >= fz["thresholds"]["B10"]["theta"]).sum()))


if __name__ == "__main__":
    main()
